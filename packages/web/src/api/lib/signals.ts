/** Signals with their raw weights renormalised so each category sums to its published weight. */
export function weightedDefs(): (SignalDef & { weight: number })[] {
  return SIGNALS.map((s, i) => {
    const cat = CATEGORIES.find((c) => c.key === s.category);
    const catWeight = cat ? cat.weight : 0;
    const rawSum = SIGNALS.filter((o) => o.category === s.category).reduce((a, o) => a + o.raw, 0);
    return { ...s, weight: (s.raw / rawSum) * catWeight, sortOrder: i };
  });
}

export const SIGNAL_BY_KEY = new Map(SIGNALS.map((s) => [s.key, s]));
