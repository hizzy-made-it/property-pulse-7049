/**
 * The signal registry — 40 weighted inputs across the 5 published categories.
 *
 * 17 core signals come from SCORING_SIGNALS_AND_ACCURACY (published weights).
 * 23 "edge" signals are leading indicators: publicly obtainable, painful to track
 * by hand, and they move before price does. They carry a lead-time band and a
 * why-nobody-tracks-this line, and they feed the SAME single investment score.
 *
 * Category weights are fixed. Within a category, raw weights are renormalised so
 * the category sums to its published weight — so adding signal 41 never changes
 * what a category is worth.
 */

