export async function seed() {
  await db.delete(zips);
  await db.delete(properties);
  await db.delete(leads);
  await db.delete(improvements);
  await db.delete(contractors);
  await db.delete(projects);
  await db.delete(alerts);
  await db.delete(leaderboardMembers);

  await db.insert(zips).values(
    ZIPS.map(([zip, name, county, avgPrice, emergingScore, priceVelocity, permits, inventoryMonths, medianIncome, employment]) => ({
      zip: zip as string,
      name: name as string,
      county: county as string,
      avgPrice: avgPrice as number,
      emergingScore: emergingScore as number,
      priceVelocity: priceVelocity as number,
      permits: permits as number,
      inventoryMonths: inventoryMonths as number,
      medianIncome: medianIncome as number,
      employment: employment as number,
    })),
  );

  await db.insert(properties).values(PROPS.map((p) => ({ ...p, state: "FL", status: "ACTIVE" })));
  await db.insert(leads).values(LEADS);

  await db.insert(improvements).values(
    IMPROVEMENTS.map(([id, name, cost, value, sortOrder]) => ({
      id: id as string,
      name: name as string,
      cost: cost as number,
      value: value as number,
      sortOrder: sortOrder as number,
    })),
  );

  await db.insert(contractors).values(
    CONTRACTORS.map(([id, name, trade, zipList, rating, jobs, leadTime, match]) => ({
      id: id as string,
      name: name as string,
      trade: trade as string,
      zips: zipList as string,
      rating: rating as number,
      jobs: jobs as number,
      leadTime: leadTime as string,
      match: match as number,
    })),
  );

  await db.insert(projects).values(
    PROJECTS.map(([id, title, addr, zip, scope, value, stage, starts]) => ({
      id: id as string,
      title: title as string,
      addr: addr as string,
      zip: zip as string,
      scope: scope as string,
      value: value as number,
      stage: stage as string,
      starts: starts as string,
    })),
  );

  await db.insert(alerts).values(
    ALERTS.map(([id, zip, signal, detail, firedAt]) => ({
      id: id as string,
      zip: zip as string,
      signal: signal as string,
      detail: detail as string,
      firedAt: firedAt as string,
    })),
  );

  await db.insert(leaderboardMembers).values(
    BOARD_MEMBERS.map(([league, name, ticker, anonymous, tier, seasonPp, delta7d, rankDelta], i) => ({
      id: `lb${i + 1}`,
      league,
      name,
      ticker,
      anonymous,
      tier,
      seasonPp,
      delta7d,
      rankDelta,
      season: SEASON,
    })),
  );

  return { zips: ZIPS.length, properties: PROPS.length, leads: LEADS.length };
}

if (import.meta.main) {
  const result = await seed();
  console.log("seeded", result);
}
